package com.bukang.payout.domain;

/**
 * 정산 생성 실패 종류 (BUK-60). 관리자가 코드 표를 찾지 않고 읽도록 상수 이름 자체를 한글로 둔다
 * DB는 ENUM 칸이다. 값을 더하면 같은 PR에 ENUM 목록을 바꾸는 Flyway SQL을 넣는다 (PayoutEnumColumnTest가 확인)
 */
public enum PayoutCreateFailureType {
	// 판매자 × 대회: 참가권에 복사된 대회일이 상품의 대회일과 다르다
	주문_정산_대회일_불일치,
	// 판매자 × 대회: 예치금(캐시) 서비스에서 정산 계좌 등록 여부를 받지 못했다
	정산_계좌_조회_실패,
	// 판매자 × 대회: 정산 내역을 DB에 저장하지 못했다
	정산_저장_실패,
	// 판매자 × 대회: 정산 내역이 이미 있는지 확인하는 DB 조회가 실패했다
	정산_조회_실패,
	// 판매자 × 대회: 위에 없는 예외
	알_수_없는_실패,
	// 상품 서비스에서 대상 대회 목록을 받지 못했다 (판매자 · 대회 칸 없음, 비고에 본 기간)
	대회_조회_실패,
	// 주문 서비스에서 대회의 판매 값을 받지 못했다 (판매자 칸 없음)
	주문_조회_실패,
	// 판매자 × 대회: 실패는 아니지만 알아야 하는 건. 취소 중 참가권이 있거나 상태를 몰라 최종 정산 미룸을 했다. 실행마다 한 줄 남는다 (BUK-52)
	취소_중이라_미룸,
	// 정산 대사: 주문 판매와 정산 내역이 어긋났다 (BUK-67). 무엇이 어긋났는지는 비고에 쓴다
	대사_불일치,
	// 지급 배치: 지급 결과를 3번 몰라 지급_확인_필요로 멈췄다 (BUK-166). 비고에 정산 ID · 금액 · 횟수를 쓴다
	지급_확인_필요
}
